// Warudo exports loose C# scripts in the mod directory. Package assemblies are not portable.
using System;
using System.IO;
using System.Security.Cryptography;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace UniVRMXT.Mtoonxt.Editor
{
    [InitializeOnLoad]
    public static class VrmxtWarudoShadowExport
    {
        const string Pending = "UniVRMXT.WarudoShadowPrefab";
        const string RuntimeFile = "WarudoVrmxtShadowRuntime.cs";

        static VrmxtWarudoShadowExport() { Resume(); }

        [UnityEditor.Callbacks.DidReloadScripts]
        static void Resume()
        {
            EditorApplication.update -= Finish;
            if (!string.IsNullOrEmpty(SessionState.GetString(Pending, "")))
                EditorApplication.update += Finish;
        }

        [MenuItem("Assets/VRMXT/Prepare character shadow receivers for Warudo", true)]
        static bool CanPrepare()
        {
            var go = Selection.activeObject as GameObject;
            return go && AssetDatabase.GetAssetPath(go).StartsWith("Assets/", StringComparison.Ordinal)
                && AssetDatabase.GetAssetPath(go).EndsWith(".prefab", StringComparison.OrdinalIgnoreCase)
                && (go.GetComponentInChildren<VrmxtShadowRuntime>(true) || go.GetComponent<VrmxtMaterialsMtoonxtInstance>());
        }

        const string Stamp = "// Generated by UniVRMXT; body SHA-256 ";
        static string Hash(string text)
        {
            using (var sha = SHA256.Create())
                return BitConverter.ToString(sha.ComputeHash(Encoding.UTF8.GetBytes(text))).Replace("-", "");
        }

        static bool IsOriginalGeneratedScript(string text)
        {
            int line = text.IndexOf('\n');
            return line > 0 && text.Substring(0, line) == Stamp + Hash(text.Substring(line+1));
        }

        [MenuItem("Assets/VRMXT/Prepare character shadow receivers for Warudo")]
        static void Prepare()
        {
            PreparePrefab(AssetDatabase.GetAssetPath(Selection.activeObject));
        }

        public static void PreparePrefab(string prefab, bool geometricOutlineNormals = false)
        {
            var asset = AssetDatabase.LoadAssetAtPath<GameObject>(prefab);
            if (!asset || !prefab.StartsWith("Assets/", StringComparison.Ordinal) ||
                !prefab.EndsWith(".prefab", StringComparison.OrdinalIgnoreCase))
                throw new ArgumentException("An editable character prefab under Assets is required.", nameof(prefab));
            var runtime = asset.GetComponentInChildren<VrmxtShadowRuntime>(true);
            if (!runtime && asset.GetComponent<VrmxtMaterialsMtoonxtInstance>())
            {
                var contents = PrefabUtility.LoadPrefabContents(prefab);
                try {
                    contents.AddComponent<VrmxtShadowRuntime>().enabled = false;
                    PrefabUtility.SaveAsPrefabAsset(contents, prefab);
                } finally { PrefabUtility.UnloadPrefabContents(contents); }
                runtime = AssetDatabase.LoadAssetAtPath<GameObject>(prefab).GetComponent<VrmxtShadowRuntime>();
            }
            if (!runtime) return;
            var path = Path.Combine(Path.GetDirectoryName(prefab), RuntimeFile).Replace('\\','/');
            var source = MonoScript.FromMonoBehaviour(runtime);
            var guid = AssetDatabase.AssetPathToGUID(Path.GetDirectoryName(prefab).Replace('\\','/'));
            var code = source.text.Replace("VrmxtShadowRuntime", "WarudoVrmxtShadowRuntime")
                .Replace("namespace UniVRMXT.Mtoonxt", "namespace UniVRMXT.WarudoMods.M" + guid);
            code = Stamp + Hash(code) + "\n" + code;
            SessionState.SetBool(Pending + ".geometricOutline", geometricOutlineNormals);
            SessionState.SetString(Pending, prefab);
            if (File.Exists(path) && File.ReadAllText(path) == code) { Finish(); return; }
            // A differing source may have been intentionally edited by the artist.
            if (File.Exists(path) && !IsOriginalGeneratedScript(File.ReadAllText(path))) {
                SessionState.EraseString(Pending);
                Debug.LogError("Warudo shadow runtime already exists with different contents at " + path);
                return;
            }
            File.WriteAllText(path, code);
            AssetDatabase.ImportAsset(path);
            Resume();
        }

        static void Finish()
        {
            var path = SessionState.GetString(Pending, "");
            if (path.Length == 0 || EditorUtility.scriptCompilationFailed)
            {
                EditorApplication.update -= Finish;
                return;
            }
            if (EditorApplication.isUpdating || EditorApplication.isCompiling) return;
            var scriptPath = Path.Combine(Path.GetDirectoryName(path), RuntimeFile).Replace('\\','/');
            var script = AssetDatabase.LoadAssetAtPath<MonoScript>(scriptPath);
            if (!script || script.GetClass() == null) return;
            EditorApplication.update -= Finish;
            SessionState.EraseString(Pending);
            var prefab = PrefabUtility.LoadPrefabContents(path);
            try {
                foreach (var original in prefab.GetComponentsInChildren<VrmxtShadowRuntime>(true)) {
                    VrmxtWarudoStencilBake.Prepare(path, original, SessionState.GetBool(Pending + ".geometricOutline", false));
                    foreach (var entry in original.materialSlots)
                        if (entry.renderer is SkinnedMeshRenderer skin && entry.authored.Length > 0 &&
                            (!skin.sharedMesh || !EditorUtility.IsPersistent(skin.sharedMesh)))
                            throw new InvalidOperationException("Warudo export requires a saved skinned mesh on " + skin.name);
                    var mirror = original.GetComponent(script.GetClass()) ?? original.gameObject.AddComponent(script.GetClass());
                    var serialized = new SerializedObject(mirror);
                    var from = new SerializedObject(original);
                    serialized.CopyFromSerializedProperty(from.FindProperty("policies"));
                    serialized.CopyFromSerializedProperty(from.FindProperty("materialSlots"));
                    serialized.ApplyModifiedPropertiesWithoutUndo();
                    // Only the portable script should run on this exported prefab.
                    original.enabled = false;
                }
                PrefabUtility.SaveAsPrefabAsset(prefab, path);
                Debug.Log("Warudo shadow receiver policies prepared on " + path);
            } finally { PrefabUtility.UnloadPrefabContents(prefab); }
        }
    }
}
